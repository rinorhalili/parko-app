import { writeFile } from 'node:fs/promises'

const sourceUrl = 'https://prishtinaparking.net/harta/'
const response = await fetch(sourceUrl)
if (!response.ok) throw new Error(`Prishtina Parking returned ${response.status}`)
const html = await response.text()
const start = html.indexOf('var umsAllMapsInfo = ')
const end = html.indexOf('];', start)
if (start < 0 || end < 0) throw new Error('Official parking map data was not found')

const maps = JSON.parse(html.slice(start + 'var umsAllMapsInfo = '.length, end + 1))
const markers = maps[0]?.markers ?? []
if (markers.length < 100) throw new Error(`Expected at least 100 official markers, got ${markers.length}`)

const decodeHtml = (value) => value
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/gi, ' ')
  .replace(/&amp;/gi, '&')
  .replace(/\s+/g, ' ')
  .trim()

const records = markers.map((marker) => {
  const title = marker.title.trim()
  const normalized = title.toLocaleLowerCase('sq')
  const description = decodeHtml(marker.description ?? '')
  const code = title.match(/^([A-Z]+\d+)/)?.[1] ?? null
  const category = normalized.includes('rezidencial')
    ? 'residential'
    : normalized.includes('komercial')
      ? 'commercial'
      : normalized.includes('kombinuar')
        ? 'combined'
        : normalized.includes('me laure')
          ? 'barrier'
          : 'commercial'
  const capacityMatch = description.match(/Vendparkingje:\s*(\d+)/i)
  const parsedPrice = /50\s*cent/i.test(description)
    ? 0.5
    : /1\s*euro/i.test(description)
      ? 1
      : null
  const pricePerHour = parsedPrice ?? (['K1', 'K2', 'K3', 'X6'].includes(code) ? 1 : 0.5)
  const address = title.match(/,\s*(rr\.?\s*.+)$/i)?.[1] ?? 'Prishtinë'
  return {
    markerId: String(marker.id),
    code,
    title,
    address,
    lat: Number(marker.coord_x),
    lng: Number(marker.coord_y),
    capacity: capacityMatch ? Number(capacityMatch[1]) : null,
    pricePerHour,
    category,
  }
})

const output = `import type { MunicipalParkingCategory } from './types'\n\nexport type OfficialPrishtinaParkingMarker = {\n  markerId: string\n  code: string | null\n  title: string\n  address: string\n  lat: number\n  lng: number\n  capacity: number | null\n  pricePerHour: number | null\n  category: MunicipalParkingCategory\n}\n\n// Source: ${sourceUrl}\n// Generated by: npm run parking:sync:official\nexport const OFFICIAL_PRISHTINA_PARKING_MARKERS: OfficialPrishtinaParkingMarker[] = ${JSON.stringify(records, null, 2)}\n`
await writeFile('src/officialPrishtinaParking.ts', output)
console.log(`Synced ${records.length} official parking markers from ${sourceUrl}`)
